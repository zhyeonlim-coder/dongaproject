/* ==========================================================================
   specs-baseline.js — 규격(Spec) 원본  ·  window.SPECS_BASELINE

   왜 이 파일이 있는가
     규격 한계값은 Pass/Fail 판정의 근거이고, 판정 결과는 규제 문서에
     실립니다. 그 기준이 사용자 브라우저의 localStorage 에만 있으면
     캐시를 한 번 지우는 것으로 사라지고, 그 순간부터 판정은 말없이
     "규격 없음" 으로 되돌아갑니다. 사라진 줄 아무도 모릅니다.

     그래서 원본은 이 파일입니다. 저장소에 커밋되어 있고, 이력이 git 에
     남고, 브라우저를 지워도 그대로입니다.

   지금 비어 있는 이유
     규격 값은 규제 문서의 내용입니다. 그럴듯한 숫자를 여기 심어 두면
     화면에는 판정이 뜨지만 그 판정에는 근거가 없습니다. 실제 문서에서
     옮겨 적기 전까지는 비워 둡니다 — "판정할 수 없다" 가 맞는 답입니다.

   어떻게 채우는가
     화면(규격 관리 탭)에서 등록하면 브라우저에 임시(pending)로 쌓입니다.
     그 상태는 캐시를 지우면 사라지므로, 화면이 계속 경고합니다.
     "저장소 파일로 내보내기" 를 누르면 이 파일의 새 내용이 나옵니다.
     그것으로 이 파일을 교체하고 커밋하면 그때부터 원본이 됩니다.

   ★ 이 파일이 로드되지 않으면 규격 판정을 하지 않습니다.
     "규격이 없다" 와 "규격 원본을 읽지 못했다" 는 다른 상황이고,
     후자를 전자처럼 답하면 그것이 바로 조용한 오답입니다.
   ========================================================================== */

